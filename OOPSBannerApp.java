
class BannerPatterns {
    

    public void printOOPS() {

        System.out.println("  *** " + "  *** " + " ****** " + "  ***** ");
        

        System.out.println(" * * " + " * * " + " * * " + " * ");
        
        System.out.println(" * * " + " * * " + " * * " + " * ");
        

        System.out.println(" * * " + " * * " + " ****** " + "  ***** ");
        
        
        System.out.println(" * * " + " * * " + " * " + "       * ");
        
       
        System.out.println(" * * " + " * * " + " * " + "       * ");
        
       
        System.out.println("  *** " + "  *** " + " * " + "  ***** ");
    }
}

public class OOPSBannerApp {

    public static void main(String[] args) {
        
        BannerPatterns patterns = new BannerPatterns();
        
      
        patterns.printOOPS();
    }
}